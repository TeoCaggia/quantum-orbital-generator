export function naturalIsotopes(symbol) {
  return [...(NATURAL_ISOTOPES[symbol] || [])]
    .sort((left, right) => Number(right[1]) - Number(left[1]));
}

export function isotopicAbundancePercent(fraction) {
  if (fraction === '1') return '100%';
  const decimalPlaces = Math.max(0, (fraction.split('.')[1]?.length || 0) - 2);
  return `${(Number(fraction) * 100).toFixed(decimalPlaces)}%`;
}
